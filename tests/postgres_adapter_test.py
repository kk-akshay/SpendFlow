"""Pure SQL compatibility checks; no external PostgreSQL connection required."""
from backend.postgres import _convert_sql, pg_schema
from backend.db import SCHEMA


def test_boolean_progress_aggregate():
    sql, _ = _convert_sql("SELECT SUM(t.status='categorized') done FROM transactions t WHERE user_id=?")
    assert "SUM(CASE WHEN t.status='categorized' THEN 1 ELSE 0 END)" in sql
    assert "user_id=%s" in sql


def test_sqlite_date_sort():
    sql, _ = _convert_sql("ORDER BY ABS(julianday(t.date)-julianday(?))")
    assert "julianday" not in sql.lower()
    assert "t.date::date - %s::date" in sql


def test_ignore_and_insert_ids():
    sql, returned = _convert_sql("INSERT OR IGNORE INTO categories(user_id,name) VALUES(?,?)")
    assert "ON CONFLICT DO NOTHING" in sql
    assert "RETURNING id" in sql
    assert returned


def test_pg_schema():
    ddl = "\n".join(pg_schema(SCHEMA))
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "BYTEA" in ddl
    assert "datetime('now')" not in ddl
    assert "PRAGMA" not in ddl


if __name__ == "__main__":
    test_boolean_progress_aggregate()
    test_sqlite_date_sort()
    test_ignore_and_insert_ids()
    test_pg_schema()
    print("PostgreSQL SQL adapter checks passed")
